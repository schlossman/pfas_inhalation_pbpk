chloroform.Take.oral <- function(){
  # Creates manuscript Figure S-5
  
  TSTOP = 600         # Simulation time (min).
  CINT = 0.1          # Frequency with which solver should report results (min).
  times = seq(from=0, to=TSTOP, by=CINT)
  
  # Import data 
  take_data = read_excel("Data/Data_CF/Take_data.xlsx", sheet = "oral")
  take_acslx_oral_output <- read_excel("Data/Data_CF/Take_acslx_output.xlsx", 
                                       sheet = "oral")
  
  # Simulates male rats exposed to an oral dose of chloroform
  out <- PBPK_run(model.param.filename = "CF_template_parameters_Model.xlsx",
                  model.param.sheetname = "Revised_rat_params",
                  exposure.param.filename = "CF_template_parameters_Exposure.xlsx", 
                  exposure.param.sheetname = "Take_oral",
                  data.times = times)
  
  # Time in minutes
  time_min <- out[,"time"]*60
  time_min1 <- time_min[10:5500]
  
  # Generate a figure that shows blood concentrations vs. time.
  C_ven_out <- out[,"C_ven"]
  C_ven_out1 <- C_ven_out[10:5500]
  
  df_C_ven = data.frame(time_min, C_ven_out)
  
  is.na(df_C_ven[df_C_ven==0]) <- TRUE
  
  bl_min = data.frame(Time=c(take_data[,1]),
                      Conc=c(take_data[,2]))
  bl_data = data.frame(Time=c(take_data[,1]),
                       Conc=c(take_data[,3]))
  bl_max = data.frame(Time=c(take_data[,1]),
                      Conc=c(take_data[,4]))
  
  bl_acslx_model = data.frame(time_acslx_mod=c(take_acslx_oral_output[,1]),
                              ven_bl_acslx_mod=c(take_acslx_oral_output[,2]))
  
  par(mfrow = c(2, 2), mar = c(5, 5, 0, 0), oma = c(3, 0, 1, 2))
  
  plot(time_min1, C_ven_out1, type="l", lwd=4, lty=templ.lty, cex = 0.2, col=templ.col, 
       log="y", cex.main = 0.8, xlab="Time (min)",  
       ylab="Blood Concentration (mg/L)",
       xlim=c(0, 500), ylim=c(0.005, 100.0), cex.lab = 1.25, yaxt="n", xaxt="n")
  axis(side=1, at=seq(from=0, to=500, by=100), cex.axis = 1.2)
  axis(side=2, at=c(0.001, 0.01, 0.1, 1.0, 10.0, 100.0),
       labels=c(0.001, 0.01, 0.1, 1.0, 10.0, 100.0), cex.axis = 1.2, las=1)
  points(bl_min$time[1:7], bl_min$blood_min[1:7], type="p", pch=8,
         cex=1.5, col=pub.col)
  points(bl_data$time[1:7], bl_data$blood_data[1:7], type="p", pch=19,
         cex=1.5, col=pub.col)
  points(bl_max$time[1:7], bl_max$blood_max[1:7], type="p", pch=8,
         cex=1.5, col=pub.col)
  lines(bl_acslx_model$time, bl_acslx_model$blood_conc, 
        lwd=4, cex = 0.2, lty=pub.lty,
        col=pub.col)
  
  # Generate a figure that shows fat concentrations vs. time.
  fat_out <- out[,"C_tc3"] * 0.9
  fat_out1 <- fat_out[10:5500]
  is.na(fat_out[fat_out==0]) <- TRUE
  
  fat_min = data.frame(Time=c(take_data[,1]),
                       Conc=c(take_data[,5]))
  fat_data = data.frame(Time=c(take_data[,1]),
                        Conc=c(take_data[,6]))
  fat_max = data.frame(Time=c(take_data[,1]),
                       Conc=c(take_data[,7]))
  
  fat_acslx_model = data.frame(time_acslx_mod=c(take_acslx_oral_output[,1]),
                               fat_acslx_mod=c(take_acslx_oral_output[,3]))
  
  #par(mar=c(3.3, 3.1, 2.2, 1.1), mgp = c(2, 0.5, 0))
  plot(time_min1, fat_out1, type="l", lwd=4, lty=1, col=templ.col, log="y",
       cex.main = 0.8, xlab="Time (min)",  
       ylab="Fat Concentration (mg/L)",
       xlim=c(0, 500), ylim=c(0.005, 100.0), cex.lab = 1.25, yaxt="n", xaxt="n")
  axis(side=1, at=seq(from=0, to=500, by=100), cex.axis = 1.2)
  axis(side=2, at=c(0.001, 0.01, 0.1, 1.0, 10.0, 100.0),
       labels=c(0.001, 0.01, 0.1, 1.0, 10.0, 100.0), cex.axis = 1.2, las=1)
  points(fat_data$time[1:7], fat_data$fat_data[1:7], type="p", pch=19,
         cex=1.5, col=pub.col)
  points(fat_max$time[1:7], fat_max$fat_max[1:7], type="p", pch=8,
         cex=1.5, col=pub.col)
  points(fat_min$time[1:7], fat_min$fat_min[1:7], type="p", pch=8,
         cex=1.5, col=pub.col)
  lines(fat_acslx_model$time, fat_acslx_model$fat_conc, lwd=4, cex = 0.2, lty=pub.lty,
        col=pub.col)
  
  # Generate a figure that shows kidney concentrations vs. time.
  kid_out <- (out[,"A_ki"] + out[,"A_om"]) / (out[,"V_ki"] + out[,"V_om"])
  kid_out1 <- kid_out[10:5500]
  is.na(kid_out[kid_out==0]) <- TRUE
  
  kid_min = data.frame(Time=c(take_data[,1]),
                       Conc=c(take_data[,8]))
  kid_data = data.frame(Time=c(take_data[,1]),
                        Conc=c(take_data[,9]))
  kid_max = data.frame(Time=c(take_data[,1]),
                       Conc=c(take_data[,10]))
  
  kid_acslx_model = data.frame(time_acslx_mod=c(take_acslx_oral_output[,1]),
                               kid_acslx_mod=c(take_acslx_oral_output[,4]))
  
  #par(mar=c(3.3, 3.1, 2.2, 1.1), mgp = c(2, 0.5, 0))
  plot(time_min1, kid_out1, type="l", lwd=4, lty=1, col=templ.col, log="y",
       cex.main = 0.8, xlab="Time (min)",  
       ylab="Kidney Concentration (mg/L)",
       xlim=c(0, 500), ylim=c(0.005, 100.0), cex.lab = 1.25, yaxt="n", xaxt="n")
  axis(side=1, at=seq(from=0, to=500, by=100), cex.axis = 1.2)
  axis(side=2, at=c(0.001, 0.01, 0.1, 1.0, 10.0, 100.0),
       labels=c(0.001, 0.01, 0.1, 1.0, 10.0, 100.0), cex.axis = 1.2, las=1)
  points(kid_min$time[1:7], kid_min$kidney_min[1:7], type="p", pch=8,
         cex=1.5, col=pub.col)
  points(kid_data$time[1:7], kid_data$kidney_data[1:7], type="p", pch=19,
         cex=1.5, col=pub.col)
  points(kid_max$time[1:7], kid_max$kidney_max[1:7], type="p", pch=8,
         cex=1.5, col=pub.col)
  lines(kid_acslx_model$time, kid_acslx_model$kidney_conc, lwd=4, cex = 0.2, lty=pub.lty,
        col=pub.col)
  
  #Generate a figure that shows liver concentrations vs. time.
  liv_out <- out[,"C_li"]
  liv_out1 <- liv_out[10:5500]
  is.na(liv_out[liv_out==0]) <- TRUE
  
  liv_min = data.frame(Time=c(take_data[,1]),
                       Conc=c(take_data[,11]))
  liv_data = data.frame(Time=c(take_data[,1]),
                        Conc=c(take_data[,12]))
  liv_max = data.frame(Time=c(take_data[,1]),
                       Conc=c(take_data[,13]))
  
  liv_acslx_model = data.frame(time_acslx_mod=c(take_acslx_oral_output[,1]),
                               liv_acslx_mod=c(take_acslx_oral_output[,5]))
  
  #par(mar=c(3.3, 3.1, 2.2, 1.1), mgp = c(2, 0.5, 0))
  plot(time_min1, liv_out1, type="l", 
       lwd=4, lty=templ.lty, cex = 0.2, col=templ.col, 
       log="y", 
       cex.main = 0.8, xlab="Time (min)",  
       ylab="Liver Concentration (mg/L)",
       xlim=c(0, 500), ylim=c(0.005, 100.0), cex.lab = 1.25, yaxt="n", xaxt="n")
  axis(side=1, at=seq(from=0, to=500, by=100), cex.axis = 1.2)
  axis(side=2, at=c(0.001, 0.01, 0.1, 1.0, 10.0, 100.0),
       labels=c(0.001, 0.01, 0.1, 1.0, 10.0, 100.0), cex.axis = 1.2, las=1)
  points(liv_min$time[1:7], liv_min$liver_min[1:7], type="p", pch=8,
         cex=1.5, col=pub.col)
  points(liv_data$time[1:7], liv_data$liver_data[1:7], type="p", pch=19,
         cex=1.5, col=pub.col)
  points(liv_max$time[1:7], liv_max$liver_max[1:7], type="p", pch=8,
         cex=1.5, col=pub.col)
  lines(liv_acslx_model$time, liv_acslx_model$liver_conc, lwd=4, cex = 0.2, lty=pub.lty,
        col=pub.col)
  
  par(mfrow = c(1,1), oma = c(0, 0, 0, 0), mar = c(0, 0, 0, 0), new = TRUE)
  plot(0, 0, type = "n", bty = "n", xaxt = "n", yaxt = "n")
  
  legend("bottomleft", c("Median Data", "Min/Max Data"),
         xpd = TRUE, inset = c(0.15, -0.01), bty = "n",
         col = c(pub.col, pub.col),
         lty = c(NA,NA),
         pch = c(19,8), lwd = c(1,2), cex=1.12)

  legend("bottomleft", c("Sasso et al. (2013) Model", "Template Version"),
         xpd = TRUE, inset = c(0.57, -0.01), bty = "n",
         col = c(pub.col, templ.col),
         lty = c(pub.lty, templ.lty),
         pch = c(NA,NA), lwd = c(2,3), cex=1.12)
}


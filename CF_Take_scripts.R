chloroform.Take.oral.percent.diffs <- function(){
  # Calculate error: percent difference between template and acslx models
  # Discard first data point at time = 0, C_ven = 0
  
  # Import data 
  take_data = read_excel("Data/Data_CF/Take_data.xlsx", sheet = "oral")
  take_acslx_oral_output = read_excel("Data/Data_CF/Take_acslx_output.xlsx", sheet = "oral")
  
  out <- PBPK_run(model.param.filename = "CF_template_parameters_Model.xlsx", 
                  model.param.sheetname = "Revised_rat_params", 
                  exposure.param.filename = "CF_template_parameters_Exposure.xlsx", 
                  exposure.param.sheetname = "Take_oral")
  
  # Time in minutes
  time_min <- out[,"time"]*60
  time <- time_min
  
  ntimes_acslx = length(take_acslx_oral_output[["time"]])
  ntimes_template = length(out[,"time"])
  
  C_ven_out <- out[,"C_ven"]
  fat_out <- out[,"C_tc3"] * 0.9
  kid_out <- (out[,"A_ki"] + out[,"A_om"]) / (out[,"V_ki"] + out[,"V_om"])
  liv_out <- out[,"C_li"]
  
  print("The following values are calculated from the oral route models.")
  
  bl_acslx_model = data.frame(time_acslx_mod=c(take_acslx_oral_output[,1]),
                              ven_bl_acslx_mod=c(take_acslx_oral_output[,2]))
  bl_template_model = data.frame(time, C_ven_out)
  bl_acslx_model = bl_acslx_model[rowSums(bl_acslx_model[])>0,]
  df_acslx_temp_merge <- merge(na.omit(bl_acslx_model), 
                               na.omit(bl_template_model), by.x='time')
  err_bl_temp_acslx_oral = max(abs(perc.diff(df_acslx_temp_merge[,"C_ven_out"], 
                                             df_acslx_temp_merge[,"blood_conc"])))
  
  print("Maximum percentage difference between template and acslx models")
  print(paste0("  in blood compartment:  ", err_bl_temp_acslx_oral))
  
  fat_acslx_model = data.frame(time_acslx_mod=c(take_acslx_oral_output[,1]),
                               fat_acslx_mod=c(take_acslx_oral_output[,3]))
  fat_template_model = data.frame(time, fat_out)
  fat_acslx_model = fat_acslx_model[rowSums(fat_acslx_model[])>0,]
  fat_acslx_temp_merge <- merge(na.omit(fat_acslx_model), 
                                na.omit(fat_template_model), by.x='time')
  err_fat_temp_acslx_oral = max(abs(perc.diff(fat_acslx_temp_merge[,"fat_out"], 
                                              fat_acslx_temp_merge[,"fat_conc"])))
  
  print(paste0("  in fat compartment:    ", err_fat_temp_acslx_oral))
  
  
  kid_acslx_model = data.frame(time_acslx_mod=c(take_acslx_oral_output[,1]),
                               kid_acslx_mod=c(take_acslx_oral_output[,4]))
  kid_template_model = data.frame(time, kid_out)
  kid_acslx_model = kid_acslx_model[rowSums(kid_acslx_model[])>0,]
  kid_acslx_temp_merge <- merge(na.omit(kid_acslx_model), 
                                na.omit(kid_template_model), by.x='time')
  err_kid_temp_acslx_oral = max(abs(perc.diff(kid_acslx_temp_merge[,"kid_out"], 
                                              kid_acslx_temp_merge[,"kidney_conc"])))
  
  print(paste0("  in kidney compartment: ", err_kid_temp_acslx_oral))
  
  
